package com.educacion.plataforma.controller;

import com.educacion.plataforma.dto.EstadisticaCurso;
import com.educacion.plataforma.service.EstadisticaService;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
/**
 *
 * @author Willi
 */


@RestController
@RequestMapping("/api/estadisticas")
public class EstadisticaController {

    private final EstadisticaService estadisticaService;

    public EstadisticaController(EstadisticaService estadisticaService) {
        this.estadisticaService = estadisticaService;
    }

    @GetMapping("/curso/{cursoId}")
    public EstadisticaCurso curso(@PathVariable Long cursoId) {
        return estadisticaService.calcular(cursoId);
    }
}