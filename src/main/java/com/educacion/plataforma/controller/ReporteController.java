package com.educacion.plataforma.controller;

import com.educacion.plataforma.service.ReporteService;
import java.util.Map;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;
/**
 *
 * @author Willi
 */


@RestController
@RequestMapping("/api/reportes")
public class ReporteController {

    private final ReporteService reporteService;

    public ReporteController(ReporteService reporteService) {
        this.reporteService = reporteService;
    }

    @GetMapping("/plataforma")
    public Map<String, Object> plataforma(@RequestParam Long coordinadorId) {
        return reporteService.plataforma(coordinadorId);
    }
}